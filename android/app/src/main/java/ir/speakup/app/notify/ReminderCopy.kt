package ir.speakup.app.notify

import ir.speakup.app.domain.toPersianDigits

/**
 * متن یادآورها.
 *
 * سه قاعده که تفاوت یادآورِ مؤثر با اسپم را می‌سازند:
 *
 * **۱. عدد واقعی کاربر در متن بیاید.** «۷ واژه آماده مرور است» کار می‌کند،
 * «وقت تمرین است» نه. یادآورِ بی‌عدد، یعنی فرستنده نمی‌داند کاربر کیست.
 *
 * **۲. چیزی که در خطر است نام برده شود.** انگیزه بازگشت، از دست ندادن است
 * نه به دست آوردن. «زنجیره ۱۲ روزه‌ات» چیزی است که کاربر ساخته و باختنش
 * برایش هزینه دارد.
 *
 * **۳. لحن با هرچه دورتر شدن، نرم‌تر شود نه بلندتر.** کاربری که ده روز
 * نیامده با فریاد برنمی‌گردد؛ با تحقیر شدن حذف می‌کند. متن‌های دور، دعوت‌اند
 * نه سرزنش.
 *
 * مخاطب «تو»ست، مثل بقیه اپ.
 */
data class Reminder(val title: String, val body: String)

object ReminderCopy {

    /**
     * انتخاب متن بر پایه وضعیت واقعی کاربر.
     *
     * ترتیب شرط‌ها اهمیت دارد: از فوری‌ترین چیزی که در خطر است شروع
     * می‌شود و به عمومی‌ترین می‌رسد.
     */
    fun pick(s: ReminderState, variant: Int): Reminder? = when {
        // هدف امروز کامل شده — امروز حرفی برای گفتن نداریم
        s.goalReached -> null

        // زنجیره امشب می‌شکند. قوی‌ترین پیام ما، و فقط وقتی واقعاً چیزی
        // برای باختن هست.
        s.daysAway == 0 && s.streak > 0 && s.todayXp == 0 -> Reminder(
            "زنجیره ${s.streak.toPersianDigits()} روزه‌ات امشب می‌شکند",
            if (s.dueCount > 0)
                "یک مرور کوتاه کافی است. ${s.dueCount.toPersianDigits()} واژه آماده است."
            else "یک تمرین کوتاه نگهش می‌دارد.",
        )

        // امروز شروع کرده اما به هدف نرسیده — نزدیک‌ترین حالت به موفقیت
        s.daysAway == 0 && s.todayXp in 1 until s.goalXp -> Reminder(
            "${(s.goalXp - s.todayXp).toPersianDigits()} امتیاز تا هدف امروز",
            "همین‌قدر مانده. حیف است نیمه‌کاره بماند.",
        )

        // روز اول غیبت، با زنجیره‌ای که هنوز فریز داردش
        s.daysAway == 1 && s.streak > 0 -> Reminder(
            "دیروز جا ماند",
            if (s.freezes > 0)
                "فریزت زنجیره را نگه داشت، اما امروز دیگر فریزی در کار نیست."
            else "زنجیره ${s.streak.toPersianDigits()} روزه‌ات هنوز زنده است. امروز نگهش دار.",
        )

        s.daysAway == 1 -> Reminder("امروز چطور؟", "یک درس کوتاه، ده دقیقه.")

        // دو تا سه روز: یادآوری آرام با چیزی مشخص برای انجام دادن
        s.daysAway in 2..3 && s.dueCount > 0 -> Reminder(
            "${s.dueCount.toPersianDigits()} واژه منتظر مرورند",
            "واژه‌هایی که اشتباه زدی، الان بهترین وقتشان است.",
        )

        s.daysAway in 2..3 -> Reminder(
            "${s.daysAway.toPersianDigits()} روز گذشته",
            "از جایی که بودی ادامه بده، از اول شروع نمی‌کنی.",
        )

        // یک هفته: یادآوری ارزشِ ساخته‌شده، نه سرزنشِ نبودن
        s.daysAway in 4..7 -> when (variant % 2) {
            0 -> Reminder(
                "بلندترین زنجیره‌ات ${s.longestStreak.toPersianDigits()} روز بود",
                "دوباره ساختنش از دفعه اول آسان‌تر است.",
            )
            else -> Reminder("یک درس، ده دقیقه", "همین امروز دوباره راه بیفت.")
        }

        // دورتر از یک هفته: کم‌رفت‌وآمد و دعوت‌گونه
        else -> when (variant % 3) {
            0 -> Reminder("هنوز همین‌جاست", "پیشرفتت ذخیره است. هر وقت خواستی ادامه بده.")
            1 -> Reminder("یک واژه هم یک قدم است", "پنج دقیقه امروز، از هیچ بیشتر است.")
            else -> Reminder("درس بعدی‌ات آماده است", "از همان‌جایی که رها کردی.")
        }
    }
}

/** عکس لحظه‌ای وضعیت کاربر — ورودی تصمیمِ یادآور */
data class ReminderState(
    val streak: Int,
    val longestStreak: Int,
    val freezes: Int,
    val todayXp: Int,
    val goalXp: Int,
    val dueCount: Int,
    /** چند روز است هیچ فعالیتی تمام نکرده؛ صفر یعنی امروز فعال بوده */
    val daysAway: Int,
) {
    val goalReached: Boolean get() = goalXp > 0 && todayXp >= goalXp
}
